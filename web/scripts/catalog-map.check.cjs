// Run: APP_URL=http://127.0.0.1:3001 node web/scripts/catalog-map.check.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/Lenovo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base = process.env.APP_URL || 'http://127.0.0.1:3001';
const output = path.resolve(__dirname, '../../output/acceptance');
(async () => {
  fs.mkdirSync(output, {recursive:true});
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1050}});
  page.setDefaultTimeout(60000);
  const errors = [], mapRequests = [], productRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { const url = new URL(request.url()); if (url.pathname === '/api/map/offers') mapRequests.push(url); if (url.pathname === '/api/products') productRequests.push(url); });
  try {
    const query = new URLSearchParams({q:'هدفون',max_price:'5000000',lat:'35.7219',lng:'51.4097',radius_km:'30'});
    await page.goto(base, {waitUntil:'domcontentloaded'});
    await page.evaluate(() => localStorage.setItem('torob-in-person.workspace.v1',JSON.stringify({conversation:{location:{lat:35.7219,lng:51.4097,label:'مرکز آزمون تهران'},radiusKm:30,preferences:{}}})));
    await page.goto(base + '/products?' + new URLSearchParams({q:'هدفون',max_price:'5000000'}), {waitUntil:'domcontentloaded',timeout:90000});
    await page.waitForURL(url => ['lat','lng','radius_km'].every(key => url.searchParams.get(key) === query.get(key)));
    await page.locator('[data-testid="product-results"]').waitFor();
    assert(productRequests.length > 0 && productRequests.every(url => ['lat','lng','radius_km'].every(key => url.searchParams.has(key))),'scoped products must never fetch before geographic canonicalization');

    await page.locator('.map-shop-card').first().waitFor();
    await page.locator('.leaflet-container').waitFor();
    assert(await page.locator('.catalog-products-pane').isVisible());
    assert(await page.locator('.catalog-map-pane').isVisible());
    const boxes = await Promise.all(['.catalog-products-pane','.catalog-map-pane'].map(selector => page.locator(selector).boundingBox()));
    assert(Math.abs(boxes[0].y - boxes[1].y) < 15, 'desktop products and map must be adjacent');
    const latestMap = mapRequests.at(-1);
    for (const [key,value] of query) assert.equal(latestMap.searchParams.get(key),value);
    assert.equal(latestMap.searchParams.has('page_size'),false,'map must not be limited to one product page');
    assert.equal(latestMap.searchParams.has('product_ids'),false,'map must include every matching product');
    const currentProducts = await (await page.request.get(base + '/api/products?' + query + '&page_size=24')).json();
    assert.equal(await page.locator('.product-tile').count(), Math.min(24,currentProducts.total));
    assert.equal(Number(await page.locator('[data-testid="result-count"]').getAttribute('data-total')),currentProducts.total);
    const mappedProducts = await (await page.request.get(base + latestMap.pathname + latestMap.search)).json();
    assert.equal(currentProducts.total,mappedProducts.product_count,'products and map must have the same eligible product universe');
    for (const product of currentProducts.data) {
      const offers = mappedProducts.results.filter(result => result.offer.productId === product.id);
      assert(offers.length > 0,'each product must have an eligible map offer');
      assert.equal(product.offerCount,offers.length);
      assert.equal(product.shopCount,new Set(offers.map(result => result.shop.id)).size);
    }
    if (currentProducts.data[0]?.shopCount !== undefined) assert.match(await page.locator('.tile-counts').first().innerText(),/فروشگاه/);
    await page.waitForFunction(() => document.querySelector('.leaflet-tile-loaded') || document.querySelector('.map-tile-error'),undefined,{timeout:20000}).catch(() => console.log('Map base tiles still pending; dataset markers and list remain available'));
    await page.screenshot({path:path.join(output,'catalog-map-desktop.png')});
    await page.locator('.map-canvas-shell').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,'catalog-map-desktop-map.png')});
    const firstShop = page.locator('.map-shop-card').first();
    const shopName = await firstShop.locator('b').first().innerText();
    await firstShop.locator('.map-shop-select').click();
    await page.waitForFunction(name => document.querySelector('.leaflet-popup-content strong')?.textContent === name,shopName);
    assert(await page.locator('.map-popup-offer .offer-contact-action').first().getAttribute('href'));
    const before = new URL(page.url()).searchParams;
    await page.getByRole('slider',{name:'شعاع جستجو'}).focus();
    await page.getByRole('slider',{name:'شعاع جستجو'}).press('End');
    await page.getByRole('button',{name:'اعمال محدوده',exact:true}).click();
    await page.waitForURL(url => url.searchParams.get('radius_km') === '100');
    for (const key of ['q','max_price']) assert.equal(new URL(page.url()).searchParams.get(key),before.get(key));
    await page.locator('.map-shop-card').first().waitFor();
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'محصولات',exact:true}).click();
    assert(await page.locator('.catalog-products-pane').isVisible());
    assert.equal(await page.locator('.catalog-map-pane').isVisible(),false);
    await page.getByRole('button',{name:'نقشه و فروشگاه‌ها',exact:true}).click();
    assert(await page.locator('.catalog-map-pane').isVisible());
    assert.equal(await page.locator('.catalog-products-pane').isVisible(),false);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1),false,'mobile must not overflow');
    await page.locator('.map-canvas-shell').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,'catalog-map-mobile.png')});
    await page.evaluate(() => localStorage.setItem('torob-in-person.workspace.v1',JSON.stringify({conversation:{preferences:{},selectedShopIds:[],selectedOfferIds:[]}})));
    const contact = page.locator('.map-shop-card .offer-contact-action').first();
    const selectedId = new URL(await contact.getAttribute('href'),base).searchParams.get('offer_id');
    await contact.click();
    await page.waitForURL(url => url.pathname === '/contact' && url.searchParams.get('offer_id') === selectedId);
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('torob-in-person.workspace.v1')));
    assert(saved.conversation.selectedProductId);
    assert(saved.conversation.selectedShopIds.length === 1);
    assert.deepEqual(saved.conversation.selectedOfferIds,[selectedId]);
    await page.goto(base + '/products/' + encodeURIComponent(saved.conversation.selectedProductId),{waitUntil:'domcontentloaded'});
    await page.locator('#offers .offer-contact-action').first().waitFor();
    const detailContact = page.locator('#offers .offer-contact-action').first();
    const detailOffer = new URL(await detailContact.getAttribute('href'),base).searchParams.get('offer_id');
    assert(detailOffer);
    await detailContact.click();
    await page.waitForURL(url => url.pathname === '/contact' && url.searchParams.get('offer_id') === detailOffer);
    const detailSaved = await page.evaluate(() => JSON.parse(localStorage.getItem('torob-in-person.workspace.v1')));
    assert.deepEqual(detailSaved.conversation.selectedOfferIds,[detailOffer]);
    await page.setViewportSize({width:1440,height:1050});
    await page.goto(base + '/map?q=',{waitUntil:'domcontentloaded'});
    await page.getByText('ابتدا در صفحه محصولات جستجو کن یا یک محصول را انتخاب کن.',{exact:true}).waitFor();
    await page.route('**/api/map/offers?**',route => route.fulfill({status:503,json:{detail:'خطای بررسی نقشه'}}));
    await page.goto(base + '/products?' + query,{waitUntil:'domcontentloaded'});
    await page.getByText('خطای بررسی نقشه',{exact:true}).waitFor();
    await page.unroute('**/api/map/offers?**');
    await page.locator('.catalog-map-pane').getByRole('button',{name:'تلاش دوباره',exact:true}).click();
    await page.locator('.map-shop-card').first().waitFor({state:'attached'});
    assert.deepEqual(errors,[]);
    const report = {canonicalGeoBeforeFetch:true,matchingGeoOfferUniverse:true,desktopAdjacent:true,sharedQuery:true,allMatchingProducts:true,trueCounts:true,markerSelection:true,locationPreservesQuery:true,mobileTabs:true,horizontalOverflow:false,offerSelectionPersisted:true,detailOfferSelection:true,unscopedMapGuard:true,mapErrorRetry:true,pageErrors:errors};
    fs.writeFileSync(path.join(output,'catalog-map-report.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify(report));
  } finally { await Promise.race([browser.close(),new Promise(resolve => setTimeout(resolve,5000))]); }
})().then(() => process.exit(0)).catch(error => { console.error(error);process.exit(1); });
